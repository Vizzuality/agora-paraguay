import { categoryCountWidgets, type CategoryCountWidget } from '@/lib/analysis/category-counts';
import { indicatorCards, type IndicatorCard } from '@/lib/analysis/indicator-cards';
import { numberWidgets, type NumberWidget } from '@/lib/analysis/number-widget';
import {
  projectionCrop,
  projectionWidgets,
  type ProjectionWidget,
} from '@/lib/analysis/projection';
import { seasonBarsWidgets, type SeasonBarsWidget } from '@/lib/analysis/season-bars';
import { valueHistogramWidgets, type ValueHistogramWidget } from '@/lib/analysis/value-histogram';
import {
  isContextIndicator,
  type ParcelScope,
  withZafrinasAfterCounters,
} from '@/lib/analysis/widget-config';
import type { AnalysisParcel } from '@/lib/api/analysis/schemas';
import type { Indicator, Indicators, IndicatorsRiesgo } from '@/lib/api/metadata/schemas';
import { INDICATOR_CATEGORY_TITLES } from '@/lib/platform-metadata';

export type AnalysisWidget =
  | ({ kind: 'ruler' } & IndicatorCard)
  | ({ kind: 'bar-chart' } & CategoryCountWidget)
  | ({ kind: 'histogram' } & ValueHistogramWidget)
  | ({ kind: 'number' } & NumberWidget)
  | ({ kind: 'projection' } & ProjectionWidget)
  | ({ kind: 'seasons' } & SeasonBarsWidget);

export type AnalysisWidgetsInput = {
  /** The answer's parcels, matched by id — the backend need not echo them in request order. */
  parcels: AnalysisParcel[];
  /** The parcels Analizar submitted, in submission order. */
  parcelIds: string[];
  indicators: Indicators | undefined;
  riesgo: IndicatorsRiesgo;
  /** One parcel (a parcel tab) or the whole selection (Todas). */
  scope: ParcelScope;
  /**
   * The parcel the open tab points at — what the risk-class cards read and the only
   * parcel the value lists row — or, under Todas, the set combined (`combinedParcel`).
   */
  parcel: AnalysisParcel | null | undefined;
  /** The hero's year, productivo only: dates the projection's base. */
  year?: string;
};

/** A widget's run: Información de contexto (productivo, `isContextIndicator`) or its indicator's category. */
export type WidgetCategory = NonNullable<Indicator['category']> | 'context';

/** Context first, then agnostic widgets, then the ones reading the past, then the ones projecting ahead. */
const CATEGORY_RANK: Record<WidgetCategory, number> = {
  context: -1,
  historic: 1,
  future: 2,
};

/**
 * Show all widgets generated by the selected indicators, grouped by category (agnostic,
 * historic, future) and in metadata order within each group, regardless of their type.
 * Productivo's projection chart takes its crop's first scenario's place. Types: a risk widget for a classed reading of one parcel, a count of the parcels
 * per class, a histogram of their values over a scale, one parcel's number on that scale.
 * Which type an indicator takes is `widgetFor`'s call, by riesgo and scope; each type's
 * builder answers only the indicators that are its own, so an indicator lands in at most
 * one widget.
 */
export function analysisWidgets({
  parcels,
  parcelIds,
  indicators,
  riesgo,
  scope,
  parcel,
  year,
}: AnalysisWidgetsInput): AnalysisWidget[] {
  const cards = new Map(
    indicatorCards(parcel, indicators, riesgo, scope).map((card) => [card.id, card]),
  );
  const counts = new Map(
    categoryCountWidgets(parcels, parcelIds, indicators, riesgo, scope).map((widget) => [
      widget.id,
      widget,
    ]),
  );
  const histograms = new Map(
    valueHistogramWidgets(parcels, parcelIds, indicators, riesgo, scope).map((widget) => [
      widget.id,
      widget,
    ]),
  );
  const numbers = new Map(
    numberWidgets(parcels, parcelIds, indicators, riesgo, scope, parcel).map((widget) => [
      widget.id,
      widget,
    ]),
  );

  const seasons = new Map(
    seasonBarsWidgets(parcels, parcelIds, indicators, riesgo, scope).map((widget) => [
      widget.id,
      widget,
    ]),
  );

  // Productivo's scenarios read together as one chart per crop.
  const projections = new Map(
    (riesgo === 'productivo'
      ? projectionWidgets(parcels, parcelIds, indicators, scope, parcel, year)
      : []
    ).map((widget) => [widget.id, widget]),
  );
  const placed = new Set<string>();

  const widgets = (indicators ?? []).flatMap((indicator): AnalysisWidget[] => {
    const crop = riesgo === 'productivo' ? projectionCrop(indicator.id) : null;

    if (crop !== null) {
      const projection = projections.get(`projection_${crop}`);
      if (!projection || placed.has(projection.id)) return [];
      placed.add(projection.id);
      return [{ kind: 'projection', ...projection }];
    }

    const card = cards.get(indicator.id);
    if (card) return [{ kind: 'ruler', ...card }];

    const count = counts.get(indicator.id);
    if (count) return [{ kind: 'bar-chart', ...count }];

    const histogram = histograms.get(indicator.id);
    if (histogram) return [{ kind: 'histogram', ...histogram }];

    const number = numbers.get(indicator.id);
    if (number) return [{ kind: 'number', ...number }];

    const season = seasons.get(indicator.id);
    if (season) return [{ kind: 'seasons', ...season }];

    return [];
  });

  const categoryOf = widgetCategory(indicators, riesgo);

  // Stable: each group keeps metadata order.
  const sorted = widgets.toSorted((a, b) => rankOf(categoryOf(a)) - rankOf(categoryOf(b)));

  return riesgo === 'productivo' ? withZafrinasAfterCounters(sorted) : sorted;
}

/** A widget's category: context for the context indicators, the projection's own, else its indicator's. */
function widgetCategory(indicators: Indicators | undefined, riesgo: IndicatorsRiesgo) {
  const rank = new Map((indicators ?? []).map(({ id, category }) => [id, category]));

  return (widget: AnalysisWidget): WidgetCategory | null | undefined => {
    if (widget.kind === 'projection') return widget.category;
    if (isContextIndicator(widget.id, riesgo)) return 'context';
    // The seasons a parcel grew describe it, they do not read the past: context too.
    if (widget.kind === 'seasons' && riesgo === 'productivo') return 'context';

    return rank.get(widget.id);
  };
}

/** The title over each category's widgets (`platform-metadata.json`); agnostic ones go untitled. */
export const CATEGORY_TITLES: Record<WidgetCategory, string> = INDICATOR_CATEGORY_TITLES;

export type WidgetGroup = { key: string; title: string | null; widgets: AnalysisWidget[] };

/**
 * The sorted widgets (`analysisWidgets`) cut into runs of one category, each titled
 * (`CATEGORY_TITLES`). Without categories, one untitled run.
 */
export function widgetGroups(
  widgets: AnalysisWidget[],
  indicators: Indicators | undefined,
  riesgo: IndicatorsRiesgo,
): WidgetGroup[] {
  const categoryOf = widgetCategory(indicators, riesgo);
  const groups: WidgetGroup[] = [];

  for (const widget of widgets) {
    const category = categoryOf(widget) ?? null;
    const key = category ?? 'agnostic';
    const last = groups.at(-1);

    if (last?.key === key) last.widgets.push(widget);
    else groups.push({ key, title: category && CATEGORY_TITLES[category], widgets: [widget] });
  }

  return groups;
}

function rankOf(category: WidgetCategory | null | undefined): number {
  return category ? CATEGORY_RANK[category] : 0;
}
